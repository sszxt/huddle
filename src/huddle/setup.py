"""`huddle setup`: turn a Linux machine with Huddle installed into a node.

One idempotent pass, re-run to upgrade:

1. llama.cpp — upstream's own prebuilt release at the pin, checksum verified.
   No compiler, no headers: the build every node runs is byte-for-byte the
   same, which is exactly what the RPC version handshake demands.
2. The shared libraries it needs, from the distribution's packages.
3. A short config file, written only if there is none.
4. A systemd unit, so the node is back after every reboot.
5. Firewall rules for the local subnet. ufw on the real nodes silently drops
   new ports on the LAN, and the symptom is a timeout that looks exactly like
   a broken network.

Privileged steps go through ``sudo`` one command at a time, so a user without
passwordless sudo is asked once and nothing else runs as root. The logic is
pure functions over a small command runner, so it is testable without any of
it happening.
"""

